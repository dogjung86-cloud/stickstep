/** v3 스텝을 그대로 가져온다(li: 레슨 번호 0부터, si: 스텝 번호 0부터). */
const v3 = (li: number, si: number, type: string): Step => {
  const st = V3[li].steps[si];
  if ((st as { type?: string }).type !== type) throw new Error(`unit2v5: v3 ${li}/${si} 스텝이 ${type}이 아니다(v3 구성이 바뀌었다)`);
  return st;
};
/** v3 스텝의 사본에서 일부 글자만 바꾼다. 바꿀 문장이 v3에 없으면 조용히 넘어가지 않고 멈춘다(v3가 바뀌면 여기서 드러난다). */
const patch = (st: Step, pairs: [string, string][], over: Record<string, unknown> = {}): Step => {
  let json = JSON.stringify(st);
  for (const [from, to] of pairs) {
    const a = JSON.stringify(from).slice(1, -1);
    if (!json.includes(a)) throw new Error(`unit2v5: 바꿀 문장을 찾지 못했다: ${from.slice(0, 30)}`);
    json = json.split(a).join(JSON.stringify(to).slice(1, -1));
  }
  return { ...(JSON.parse(json) as Step), ...over } as Step;
};

