const kingdomSort = (): Step => {
  const st = v3(8, 4, "binSort") as unknown as { items: { label: string; svg?: string }[] };
  if (!st.items.some((it) => it.label === "곰팡이" && !it.svg)) throw new Error("unit2v5: v3 분류 카드의 곰팡이 그림 사정이 바뀌었다");
  return { ...st, items: st.items.map((it) => (it.label === "곰팡이" ? { ...it, svg: organism("푸른곰팡이") } : it)) } as unknown as Step;
};

