/** 정본 개념 스텝의 at번째 블록(그림)을 가져와 캡션만 바꾼다. 그림이 아니면 빈 배열(개발 서버 콘솔에 알린다). */
const figOf = (old: Step, cap: string, at = 0): Block[] => {
  const b = (old as unknown as { blocks?: Block[] }).blocks?.[at];
  if (!b || b.k !== "figure") {
    if ((import.meta as unknown as { env?: { DEV?: boolean } }).env?.DEV) console.warn("[v5] u2v6: 정본 개념 스텝에서 그림 블록을 찾지 못했다");
    return [];
  }
  return [{ ...b, cap }];
};
/** 정본 정리 스텝의 i번째 카드에서 미니 그림과 색을 가져온다. */
const lookOf = (old: Step, i: number): { art?: string; color?: string } => {
  const c = (old as unknown as { cards?: Cards }).cards?.[i];
  return { art: c?.art, color: c?.color };
};
