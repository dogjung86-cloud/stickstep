/** 선택형, OX, 복수 선택에 "몇 번째 / 모두 몇 개" 번호를 매긴다. */
export const numbered = (steps: Step[]): Step[] => {
  const of = steps.filter((st) => st.type === "quiz").length;
  let n = 0;
  return steps.map((st) => (st.type === "quiz" ? ({ ...st, n: ++n, of } as Step) : st));
};
