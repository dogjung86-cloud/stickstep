/** 발주 그림 여러 장 격자 + (가)(나)… 라벨 필. cols로 한 줄에 놓을 개수를,
 *  ratio로 칸 비율을 정한다(기본 정사각 — 원본 4:3을 자르지 않으려면 "4 / 3"). */
