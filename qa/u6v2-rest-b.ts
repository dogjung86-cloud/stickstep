    const wJar = 88;
    const bot = 168;
    const top = 52;
    const pistonY = bot - (bot - top) * c.vol;
    // 기둥이 낮은 컷(vol<0.3)은 입자를 가로로 펴고 반지름을 줄여 겹침 방지(검산 A 제안 반영).
